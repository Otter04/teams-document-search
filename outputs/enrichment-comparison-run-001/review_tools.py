"""Diagnostic export, including structurally rejected but readable responses.
Does not change frozen scoring or model responses. Semantic verdicts are authored
separately after source review, never generated by this script.
"""
import json
from pathlib import Path
import sys
HERE=Path(__file__).resolve().parent
PREP=HERE.parent/'enrichment-eval-prep-001'
sys.path.insert(0,str(PREP))
import run as evaluator
from contract import validate, unique

def export():
    entries=evaluator.load_responses(HERE/'responses')
    gold={g['doc_id']:g for g in evaluator.read(PREP/'private/gold.json')}
    rows=[]
    for (model,did),e in entries.items():
        c=e['candidate'];p=evaluator.read(PREP/'public/inputs'/f'{did}.json')
        diagnostic_decode=False
        if c is None:
            # Read-only content inspection of literal control-character failures.
            # The frozen evaluator still rejects this response; never rewrite it.
            try:
                raw=evaluator.read(Path(e['file']))['response']['choices'][0]['message']['content']
                c=json.loads(raw,strict=False,object_pairs_hook=unique)
                diagnostic_decode=True
            except (ValueError,KeyError,TypeError):pass
        if not isinstance(c,dict) or not isinstance(c.get('summary'),list): continue
        rows.append({'candidate_id':evaluator.blind_id(model,did),'doc_id':did,'response_sha256':e['response_sha256'],
          'reviewer_id':None,'reviewer_kind':None,'status':'pending',
          'diagnostic_relaxed_control_characters':diagnostic_decode,
          'delivery_errors':e['errors']+validate(c,p),
          'metadata_evidence_reviews':[],
          'sentences':[{'index':i,'source_text':s['text'],'candidate_evidence':s['evidence'],'atomic_claims':[]} for i,s in enumerate(c['summary'])],
          'gold_summary_facts':gold[did]['summary_facts']})
    evaluator.write(HERE/'review-all.template.json',sorted(rows,key=lambda r:r['candidate_id']))
    return rows

def show(ids):
    rows=export()
    gold={g['doc_id']:g for g in evaluator.read(PREP/'private/gold.json')}
    for did in ids:
        p=evaluator.read(PREP/'public/inputs'/f'{did}.json')
        print('\nDOCUMENT',did)
        for b in p['document']['blocks']:
            if b.get('text'):print(b['block_id'],b['text'])
        print('GOLD FACTS',[(f['fact_id'],f['statement']) for f in gold[did]['summary_facts']])
        for r in sorted(rows,key=lambda r:r['candidate_id']):
            if r['doc_id']!=did:continue
            print('CANDIDATE',r['candidate_id'],'DELIVERY_ERROR_COUNT',len(r['delivery_errors']))
            for s in r['sentences']:print(s['index'],s['source_text'],'CITES',s['candidate_evidence'])

if __name__=='__main__':show(sys.argv[1:])
